"""Teste de regressão do bump de versão nos LOCK FILES (`sync_version.py`, #231).

O bug: o release bumpeava os 5 manifests e esquecia os `Cargo.lock`. Os locks
guardam a versão dos crates de CAMINHO (`gp100-core`, `gp100-cli`,
`gp100-library`, `gp100-ui`) e, defasados, fazem `cargo metadata --locked` e
`cargo build --release --locked` recusarem atualizar o lock:

    error: cannot update the lock file … because --locked was passed to prevent this

Esses dois são exatamente os consumidores de release: o passo `dist-sdist` do
CI (dentro do tarball) e o `build()` do `packaging/arch/PKGBUILD`. O Windows, o
macOS e o Ubuntu não reclamam porque os jobs de build NÃO usam `--locked` — a
distribuição verde escondia a árvore inconsistente (run 38553264817).

A reescrita é de LINHA e só nos pacotes LOCAIS: pacote de caminho é o que não
tem `source = ...` no lock, então uma dependência local nova entra sem lista
mantida à mão — e dependência de terceiro nunca é tocada.
"""
import importlib.util
import pathlib
import subprocess
import sys

_SCRIPTS = pathlib.Path(__file__).resolve().parents[2] / ".github" / "scripts"
RAIZ = pathlib.Path(__file__).resolve().parents[2]

LOCK = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "gp100-core"
version = "0.1.0"

[[package]]
name = "gp100-ui"
version = "0.1.0"

[[package]]
name = "serde"
version = "1.0.219"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "0f6f0f0f"
"""


def _carregar_sync_version():
    """Importa `.github/scripts/sync_version.py` como módulo (padrão dos specs)."""
    spec = importlib.util.spec_from_file_location(
        "sync_version", _SCRIPTS / "sync_version.py"
    )
    mod = importlib.util.module_from_spec(spec)
    sys.modules["sync_version"] = mod
    spec.loader.exec_module(mod)
    return mod


def _lock(tmp_path: pathlib.Path, texto: str = LOCK) -> pathlib.Path:
    caminho = tmp_path / "Cargo.lock"
    caminho.write_text(texto, encoding="utf-8")
    return caminho


def test_locais_do_lock_ignora_pacotes_de_terceiro():
    locais = _carregar_sync_version().locais_do_lock(LOCK)
    assert locais == {"gp100-core": "0.1.0", "gp100-ui": "0.1.0"}


def test_escrever_lock_reescreve_so_os_locais(tmp_path):
    sv = _carregar_sync_version()
    caminho = _lock(tmp_path)
    assert sv.escrever_lock(caminho, "0.3.0") == 2

    texto = caminho.read_text(encoding="utf-8")
    assert 'name = "gp100-core"\nversion = "0.3.0"' in texto
    assert 'name = "gp100-ui"\nversion = "0.3.0"' in texto
    # tercero intacto + tudo o mais preservado (comentario, header, ordem)
    assert 'name = "serde"\nversion = "1.0.219"' in texto
    assert texto.startswith("# This file is automatically @generated by Cargo.")
    assert "checksum = \"0f6f0f0f\"" in texto


def test_escrever_lock_nao_suja_o_arquivo_com_a_mesma_versao(tmp_path):
    """Bump idempotente: `--set` com a versao atual nao muda uma linha."""
    sv = _carregar_sync_version()
    antes = LOCK.replace('version = "0.1.0"', 'version = "0.3.0"')
    caminho = _lock(tmp_path, antes)
    assert sv.escrever_lock(caminho, "0.3.0") == 0
    assert caminho.read_text(encoding="utf-8") == antes


def test_divergencias_de_lock_aponta_o_defasado(tmp_path):
    sv = _carregar_sync_version()
    pendentes = sv.divergencias_de_lock(_lock(tmp_path), "0.3.0")
    assert len(pendentes) == 2
    assert all("0.1.0" in p and "0.3.0" in p for p in pendentes)


def test_divergencias_de_lock_com_lock_ausente(tmp_path):
    sv = _carregar_sync_version()
    assert sv.divergencias_de_lock(tmp_path / "Cargo.lock", "0.3.0")


def test_check_do_repo_esta_verde():
    """Regressão #231 no repo REAL: lock e manifest na mesma versao.

    É este o teste que morde quando o proximo bump esquecer os locks — o gate
    local (`sync_version.py --check`) e a CI usam o mesmo comando.
    """
    resultado = subprocess.run(
        [sys.executable, str(_SCRIPTS / "sync_version.py"), "--check"],
        cwd=RAIZ,
        capture_output=True,
        text=True,
    )
    assert resultado.returncode == 0, resultado.stdout + resultado.stderr
    assert "LOCK DEFASADO" not in resultado.stdout
